// Reads and writes the generated data files (Data/<Flavor>/Generated/Recipes.lua): the writer of build_classic.mjs, and the reader of
// Forever's file, which it takes a few numbers from. parseData(text) -> { generated, recipes, items, reagents, ranks, trainers, npcs };
// toLua(v) writes one Lua value; renderData(data, generated) writes the whole file (recipes_write.mjs and the self-test use it).
//
// Lua tables with only positional entries come back as arrays ({2302,1,1}); tables with keys as objects ([818] = {...} -> "818").

const lua = (v) => {
    if (v === undefined || v === null) return "nil";
    if (typeof v === "number" || typeof v === "boolean") return String(v);
    if (typeof v === "string") {
        const escaped = v.split("\\").join("\\\\").split('"').join('\\"').split("\n").join("\\n");
        return '"' + escaped + '"';
    }
    if (Array.isArray(v)) return "{" + v.map(lua).join(",") + "}";
    return "{" + Object.entries(v).filter(([, x]) => x !== undefined && x !== null).map(([k, x]) => `${k}=${lua(x)}`).join(",") + "}";
};
export { lua as toLua };

// -- parser (the subset the writer produces: numbers, strings, booleans, nil, nested tables, [n]=, name= and positional entries)
export function parseLuaTable(src, start) {
    let p = start;
    const ws = () => { while (p < src.length && /\s/.test(src[p])) p++; };
    const value = () => {
        ws();
        const c = src[p];
        if (c === "{") return table();
        if (c === '"') return string();
        const m = /^(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?|true|false|nil)/.exec(src.slice(p, p + 40));
        if (!m) throw new Error(`unexpected '${src.slice(p, p + 20)}' at ${p}`);
        p += m[0].length;
        return m[0] === "true" ? true : m[0] === "false" ? false : m[0] === "nil" ? null : Number(m[0]);
    };
    const string = () => {
        p++; // opening quote
        let out = "";
        while (src[p] !== '"') {
            if (src[p] === "\\") {
                p++;
                out += src[p] === "n" ? "\n" : src[p];
            } else out += src[p];
            p++;
        }
        p++;
        return out;
    };
    const table = () => {
        p++; // {
        const positional = [];
        const keyed = {};
        let hasKeys = false;
        for (;;) {
            ws();
            if (src[p] === "}") { p++; break; }
            if (src[p] === "[") {
                const close = src.indexOf("]", p);
                const key = src.slice(p + 1, close).trim();
                p = close + 1;
                ws();
                p++; // =
                keyed[key.replace(/^"|"$/g, "")] = value();
                hasKeys = true;
            } else {
                const m = /^([A-Za-z_][A-Za-z0-9_]*)\s*=(?!=)/.exec(src.slice(p, p + 60));
                if (m) {
                    p += m[0].length;
                    keyed[m[1]] = value();
                    hasKeys = true;
                } else positional.push(value());
            }
            ws();
            if (src[p] === ",") p++;
        }
        if (hasKeys && positional.length) throw new Error("table mixes positional and keyed entries");
        return hasKeys ? keyed : positional;
    };
    const result = table();
    return { value: result, end: p };
}

export function parseData(text) {
    const at = text.indexOf("ns.RECIPE_DATA = ");
    if (at < 0) throw new Error("not a data file");
    const { value } = parseLuaTable(text, text.indexOf("{", at));
    return value;
}

// -- writer: the file layout recipes_write.mjs has always produced
const sorted = (o) => Object.keys(o).map(Number).sort((a, b) => a - b);
export function renderData(data, generated) {
    const { recipes, items, reagents, ranks, trainers, npcs } = data;
    return [
        "local _, ns = ...",
        "",
        "-- GENERATED by tools/classic/build_classic.mjs from open sources (the client's tables, Questie's database and CMaNGOS'). Do not edit by hand.",
        "-- Recipes of every profession: skill levels, ingredients, product, how each is learned, and the items that teach them.",
        "-- recipes[spellID] = { s skill line, n name, c {orange, yellow, green, grey}, l learned-at (when not the orange one), p {item, min, max},",
        "--   m {{item, count}...}, k source codes, g training cost, t ids of the trainers that teach it (when not every trainer of the skill), i item that teaches it }",
        "-- items[itemID] = { n name, q quality, r skill needed, lv item level, k source codes, cd common world drop, sd side,",
        "--   v vendors, d drops, dn number of droppers, qs quests { id, n, lv, f, g givers { id, n, z } }, o containers, zone }",
        "-- reagents[itemID] = { v vendors { id, n, z zones, g price, f side }, d creatures that drop it and k those skinned for it { id, n, z, lo, hi,",
        "--   pm chance in 1/100 of a percent }, f zones it is fished in { z area, pm }, g nodes { n, z zones }, c what makes it { s skill, n, i spell } }",
        "-- ranks[skill][skill it goes up to] = { b books { i item, n, v vendors as in reagents }, q quests { id, n, lv level, f A|H,",
        "--   g givers { id, n, z zones } } } (Expert Cooking, First Aid and Fishing is a book; Artisan of the three, a quest)",
        "-- trainers[skill] = { { id, n name, t title, z zones, lv level, f A|H }... }",
        "-- npcs[npcID] = { map id, x, y } where a vendor or trainer stands (x and y in percent of the map), for waypoints",
        "-- source codes: 1 crafted, 2 drop, 3 PvP, 4 quest, 5 vendor, 6 trainer, 16 gathered, 21 salvaged",
        "ns.RECIPE_DATA = {",
        `    generated = ${lua(generated)},`,
        "    recipes = {",
        ...sorted(recipes).map((id) => `        [${id}] = ${lua(recipes[id])},`),
        "    },",
        "    items = {",
        ...sorted(items).map((id) => `        [${id}] = ${lua(items[id])},`),
        "    },",
        "    reagents = {",
        ...sorted(reagents).map((id) => `        [${id}] = ${lua(reagents[id])},`),
        "    },",
        "    ranks = {",
        ...sorted(ranks).map((s) =>
            `        [${s}] = {${sorted(ranks[s]).map((c) => `[${c}]=${lua(ranks[s][c])}`).join(",")}},`),
        "    },",
        "    trainers = {",
        ...sorted(trainers).map((s) => `        [${s}] = ${lua(trainers[s])},`),
        "    },",
        "    npcs = {",
        ...sorted(npcs).map((id) => `        [${id}] = ${lua(npcs[id])},`),
        "    },",
        "}",
        "",
    ].join("\n");
}
