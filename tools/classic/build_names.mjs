// Builds Data/<Flavor>/Generated/Names.lua: the names of the world objects of a recipe data file (the containers a teaching item
// is found in, the nodes an ingredient is gathered from) in every language Questie's database translates them to. The game has no
// query for an object's name (it has for spells, items, NPCs and quests, which the addon asks it), so these come with the data.
// Keyed by the English name: a node of the data has no id, only its name.
//   node tools/classic/build_names.mjs --data <Recipes.lua> --toc <QuestieDB_<Flavor>.toc> --out <Names.lua>
import { readFileSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";
import { parseData, toLua } from "./lua_data.mjs";

const option = (name) => {
    const i = process.argv.indexOf(name);
    return i > 0 ? process.argv[i + 1] : undefined;
};
const dataFile = option("--data"), toc = option("--toc"), out = option("--out");
if (!dataFile || !toc || !out) throw new Error("usage: node build_names.mjs --data <Recipes.lua> --toc <QuestieDB_X.toc> --out <Names.lua>");
process.env.QUESTIEDB_TOC = toc;
const { object, allIds, stored, cborDecode } = await import("./questie_db.mjs");

// the objects the data names
const data = parseData(readFileSync(dataFile, "utf8"));
const wanted = new Set();
for (const item of Object.values(data.items ?? {})) for (const o of item.o ?? []) if (o.n) wanted.add(o.n);
for (const reagent of Object.values(data.reagents ?? {})) for (const g of reagent.g ?? []) if (g.n) wanted.add(g.n);

// Questie's translations: one block per locale and type, zlib CBOR, columns (1: name) aligned with the ascending object ids
const LOCALES = ["deDE", "esES", "esMX", "frFR", "koKR", "ptBR", "ruRU", "zhCN", "zhTW"];
const ids = allIds("Object");
const names = {};
for (const locale of LOCALES) {
    const block = stored(`X-l10n-${locale}-Object`);
    if (!block) continue;
    const columns = cborDecode(inflateSync(Buffer.from(block, "base64")));
    const column = (Array.isArray(columns) ? columns[0] : columns?.[1]) ?? {};
    const byName = {};
    ids.forEach((id, position) => {
        // (a map keyed by the 1-based position, sparse: the objects with no translation are left out)
        const translated = Array.isArray(column) ? column[position] : column[position + 1];
        const english = object(id)?.[1];
        if (typeof translated !== "string" || !english || !wanted.has(english) || translated === english) return;
        // (several objects can share an English name: the first translation stays)
        if (byName[english] === undefined) byName[english] = translated;
    });
    if (Object.keys(byName).length > 0) names[locale] = byName;
}

const lines = [
    "local _, ns = ...",
    "",
    "-- GENERATED by tools/classic/build_names.mjs from Questie's database. Do not edit by hand.",
    "-- The names of the world objects of the recipe data (chests, herbs, veins...) in other languages: [locale][English name] = name.",
    "ns.OBJECT_NAMES = {",
];
for (const locale of Object.keys(names).sort()) {
    lines.push(`    ${locale} = {`);
    for (const english of Object.keys(names[locale]).sort()) lines.push(`        [${toLua(english)}] = ${toLua(names[locale][english])},`);
    lines.push("    },");
}
lines.push("}", "");
writeFileSync(out, lines.join("\n"));
const counts = Object.entries(names).map(([l, m]) => `${l} ${Object.keys(m).length}`).join(", ");
console.log(`${out}: ${wanted.size} object names in the data; translated: ${counts || "none"}`);
